/**
 * Generator for vertical webhook aggregator files.
 *
 * Scans every `apps/integration-server/src/verticals/<vertical>/adapters/<slug>/webhook.ts`
 * and synthesises a vertical `webhooks.ts` mapping each slug to a
 * `WebhookHandler`. Each adapter must export a single pre-built handler
 * object — either `export const xxxWebhook: WebhookHandler = …` (lower-camel
 * slug + `Webhook` suffix) or `export const XxxWebhookHandler: WebhookHandler = …`
 * (PascalCase). Adapters without either are skipped and reported.
 *
 * Run: `pnpm tsx scripts/generate-webhook-aggregators.ts <vertical> [<vertical> ...]`
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'

const REPO_ROOT = join(import.meta.dirname, '..')
const VERTICALS_DIR = join(REPO_ROOT, 'apps/integration-server/src/verticals')

interface AdapterExport {
  slug: string
  exportName: string
}

interface SkippedAdapter {
  slug: string
  reason: string
}

function listAdapters(vertical: string): string[] {
  const dir = join(VERTICALS_DIR, vertical, 'adapters')
  if (!existsSync(dir)) return []
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort()
}

function adaptersWithWebhook(vertical: string): string[] {
  return listAdapters(vertical).filter((slug) =>
    existsSync(join(VERTICALS_DIR, vertical, 'adapters', slug, 'webhook.ts')),
  )
}

/**
 * Pick the pre-built WebhookHandler export from an adapter's webhook.ts.
 *
 * Accepts two naming conventions:
 *   - `xxxWebhook` (lower-camel slug + Webhook suffix)
 *   - `XxxWebhookHandler` (PascalCase)
 */
function findHandlerExport(filePath: string): { exportName: string } | { reason: string } {
  const src = readFileSync(filePath, 'utf8')
  // Match `export const <name>` followed by anything up to `=` (covers inline
  // type annotations like `: import('…').WebhookHandler` or `: WebhookHandler`).
  const re = /^export\s+const\s+(\w+)\b[^=]*=/gm
  let m: RegExpExecArray | null
  const candidates: string[] = []
  while ((m = re.exec(src)) !== null) {
    const name = m[1]
    if (/^[a-z]\w*Webhook$/.test(name)) candidates.push(name)
    else if (/^[A-Z]\w*WebhookHandler$/.test(name)) candidates.push(name)
  }
  if (candidates.length === 0) {
    return {
      reason: 'no WebhookHandler export — adapter must export `xxxWebhook` or `XxxWebhookHandler`',
    }
  }
  return { exportName: candidates[0] }
}

function aggregatorPreamble(vertical: string): string {
  const label = vertical.charAt(0).toUpperCase() + vertical.slice(1)
  return `/**
 * ${label} webhook handler registry. Generated by
 * scripts/generate-webhook-aggregators.ts — one entry per adapter that
 * ships a ./adapters/<slug>/webhook.ts exporting a pre-built
 * \`WebhookHandler\` object (\`xxxWebhook\` or \`XxxWebhookHandler\`).
 *
 * Re-run the generator after adding a new adapter webhook to keep this
 * file in sync — \`pnpm check:webhook-verifiers\` is the CI guard.
 */
import type { WebhookHandler } from '@opensteward/shared'

`
}

function slugToIdent(slug: string): string {
  const ident = slug
    .split(/[^a-zA-Z0-9]/)
    .filter(Boolean)
    .map((part, i) =>
      i === 0
        ? part.charAt(0).toLowerCase() + part.slice(1)
        : part.charAt(0).toUpperCase() + part.slice(1),
    )
    .join('')
  // A JS identifier may not start with a digit (e.g. slug '2c2p').
  return /^[0-9]/.test(ident) ? `_${ident}` : ident
}

function buildAggregator(vertical: string): {
  source: string
  wired: AdapterExport[]
  skipped: SkippedAdapter[]
} {
  const wired: AdapterExport[] = []
  const skipped: SkippedAdapter[] = []
  for (const slug of adaptersWithWebhook(vertical)) {
    const webhookPath = join(VERTICALS_DIR, vertical, 'adapters', slug, 'webhook.ts')
    const result = findHandlerExport(webhookPath)
    if ('reason' in result) {
      skipped.push({ slug, reason: result.reason })
      continue
    }
    wired.push({ slug, exportName: result.exportName })
  }

  const imports = wired
    .map(({ slug, exportName }) => {
      const alias = slugToIdent(slug) + 'Handler'
      return `import { ${exportName} as ${alias} } from './adapters/${slug}/webhook'`
    })
    .join('\n')

  const entries = wired
    .map(({ slug }) => {
      const alias = slugToIdent(slug) + 'Handler'
      const key = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(slug) ? slug : `'${slug}'`
      return `  ${key}: ${alias},`
    })
    .join('\n')

  const source =
    aggregatorPreamble(vertical) +
    imports +
    '\n\n' +
    'export const WEBHOOK_HANDLERS: Record<string, WebhookHandler> = {\n' +
    entries +
    '\n}\n'

  return { source, wired, skipped }
}

function main(): void {
  const argv = process.argv.slice(2)
  if (argv.length === 0) {
    console.error(
      'Usage: pnpm tsx scripts/generate-webhook-aggregators.ts <vertical> [<vertical> ...]',
    )
    process.exit(2)
  }
  for (const vertical of argv) {
    const out = join(VERTICALS_DIR, vertical, 'webhooks.ts')
    if (!existsSync(join(VERTICALS_DIR, vertical))) {
      console.error(`unknown vertical: ${vertical}`)
      process.exit(2)
    }
    const { source, wired, skipped } = buildAggregator(vertical)
    writeFileSync(out, source, 'utf8')
    console.log(`${vertical}: wired ${wired.length} adapter(s) -> ${out}`)
    if (skipped.length > 0) {
      console.log(`${vertical}: skipped ${skipped.length}:`)
      for (const s of skipped) {
        console.log(`  - ${s.slug}: ${s.reason}`)
      }
    }
  }
}

main()
