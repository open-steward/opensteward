/**
 * Alibaba.com product → canonical Product.
 *
 * Two documented shapes:
 *
 *   - a `result.products[]` row of alibaba.icbu.product.list
 *     (/alibaba/icbu/product/list, cid=1): a product summary with no price
 *     and no SKUs;
 *   - `product_info` of "Get Product Information"
 *     (/alibaba/icbu/product/get/v2, cid=11): basic_info, trade_info with
 *     sku_info[] and ISO 4217 currencies.
 *
 * Fields read are only those in each API's documented output parameters.
 * The summary's `gmt_create` / `gmt_modified` ("2020-12-22 12:00:00") carry
 * no documented time zone, so they stay in metadata rather than being given
 * one. get/v2's timestamps are "using the Unix timestamp" (milliseconds in
 * the documented example).
 */

import type { Product, ProductVariant } from '../../../schema/product'
import type { Image } from '../../../schema/shared'
import { majorToMinor } from '../../../schema/shared'
import { toIsoDatetime } from '@opensteward/shared'

// ── Raw shapes ────────────────────────────────────────────────────────────────

/** alibaba.icbu.product.list `result.products[]`. */
export interface RawAlibabaListProduct {
  /** "product Id" */
  id?: number | string
  /** "subject of the product" */
  subject?: string
  /** "keywords of the product" */
  keywords?: string[]
  /** "main images of the product" */
  main_image?: { images?: string[]; watermark?: boolean | string }
  status?: string
  category_id?: number | string
  gmt_create?: string
  gmt_modified?: string
  language?: string
  [key: string]: unknown
}

export interface RawAlibabaSaleAttribute {
  attribute_name?: string
  attribute_value?: string
  image?: { image_url?: string }
}

export interface RawAlibabaSkuInfo {
  /** "SKU id generated by alibaba.com." */
  sku_id?: number | string
  /** "SKU code for sellers to manage and identify specific product specifications" */
  sku_code?: string
  /** "It is for sku pricing." */
  sku_price?: { price?: string; currency?: string }
  inventory?: string | number
  sale_attributes?: RawAlibabaSaleAttribute[]
  [key: string]: unknown
}

/** /alibaba/icbu/product/get/v2 `product_info`. */
export interface RawAlibabaProductInfo {
  basic_info?: {
    product_id?: number | string
    title?: string
    description?: string
    product_images?: { image_url?: string }[]
    create_timestamp?: number | string
    last_modified_timestamp?: number | string
    [key: string]: unknown
  }
  category_info?: { category_id?: number | string; category_name?: string }
  trade_info?: {
    sku_info?: RawAlibabaSkuInfo[]
    [key: string]: unknown
  }
  [key: string]: unknown
}

// ── Helpers ───────────────────────────────────────────────────────────────────

function images(urls: (string | undefined)[]): Image[] | undefined {
  const out = urls
    .filter((u): u is string => typeof u === 'string' && u.length > 0)
    .map((url, position) => ({ url, position }))
  return out.length > 0 ? out : undefined
}

/**
 * One SKU → variant. Only SKUs carrying `sku_price` (both price and currency)
 * become variants: get/v2 prices a product per SKU, in tiers or as a range,
 * and only "sku pricing" gives a SKU its own price. The raw SKU list stays in
 * the product's metadata either way.
 */
export function transformVariant(
  sku: RawAlibabaSkuInfo,
  productId: string,
): ProductVariant | undefined {
  const price = sku.sku_price?.price
  const currency = sku.sku_price?.currency
  if (sku.sku_id == null || price == null || !currency) return undefined
  const amount = majorToMinor(Number(price), currency)
  if (amount === undefined) return undefined
  const attrs = (sku.sale_attributes ?? []).filter(
    (a) => typeof a.attribute_name === 'string' && typeof a.attribute_value === 'string',
  )
  return {
    id: String(sku.sku_id),
    productId,
    sku: sku.sku_code || undefined,
    title: attrs.length > 0 ? attrs.map((a) => a.attribute_value).join(' / ') : undefined,
    price: { amount, currency },
    optionValues:
      attrs.length > 0
        ? Object.fromEntries(attrs.map((a) => [a.attribute_name!, a.attribute_value!]))
        : undefined,
    metadata: sku as Record<string, unknown>,
  }
}

/** Canonical titles are required; an absent or empty source field is refused, not filled in. */
function requireTitle(value: string | undefined, what: string): string {
  if (!value) throw new Error(`Alibaba ${what}`)
  return value
}

// ── Transforms ────────────────────────────────────────────────────────────────

/** A product.list summary row → Product. */
export function transformListProduct(raw: RawAlibabaListProduct): Product {
  if (raw.id == null || raw.id === '') {
    throw new Error('Alibaba product.list row has no id')
  }
  const id = String(raw.id)
  return {
    id,
    title: requireTitle(raw.subject, `product.list row ${id} has no subject`),
    tags: Array.isArray(raw.keywords) && raw.keywords.length > 0 ? raw.keywords : undefined,
    images: images(raw.main_image?.images ?? []),
    metadata: raw as Record<string, unknown>,
  }
}

/** get/v2 `product_info` → Product. */
export function transformProductInfo(raw: RawAlibabaProductInfo): Product {
  const basic = raw.basic_info ?? {}
  if (basic.product_id == null || basic.product_id === '') {
    throw new Error('Alibaba product get/v2 response has no basic_info.product_id')
  }
  const id = String(basic.product_id)
  const variants = (raw.trade_info?.sku_info ?? [])
    .map((s) => transformVariant(s, id))
    .filter((v): v is ProductVariant => v !== undefined)
  return {
    id,
    title: requireTitle(basic.title, `product get/v2 ${id} has no basic_info.title`),
    description: basic.description || undefined,
    productType: raw.category_info?.category_name || undefined,
    variants: variants.length > 0 ? variants : undefined,
    images: images((basic.product_images ?? []).map((i) => i.image_url)),
    createdAt: toIsoDatetime(basic.create_timestamp),
    updatedAt: toIsoDatetime(basic.last_modified_timestamp),
    metadata: raw as Record<string, unknown>,
  }
}
