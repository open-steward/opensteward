/**
 * Etsy adapter for the ecommerce vertical.
 *
 * Maps Etsy's Open API v3 to the canonical ecommerce resources. Etsy is
 * a creator marketplace with a finite-listing inventory model — sellers
 * publish listings, each listing has a quantity, and buyers purchase from
 * that pool.
 *
 * Slug: `etsy` (both directory and platform identifier).
 *
 * ── Coverage ─────────────────────────────────────────────────────────────
 *
 * Implemented (23):
 *
 *   Products:     list, get, create, update, delete  (Listings API)
 *   Inventory:    listInventoryLevels, getInventoryLevel,
 *                 adjustInventoryLevel, setInventoryLevel
 *                 (Listing Inventory API)
 *   Orders:       list, get                          (Receipts API)
 *   Fulfillments: list, get, create                  (Receipt shipments)
 *   Collections:  list, get, create, update, delete  (ShopSection API)
 *   Refunds:      list, get                          (Derived from Receipt)
 *   Transactions: list, get                          (Payments API)
 *
 * ── Resource coverage ──────────────────────────────────────────────────
 * Unavailable: location — Etsy shops have no warehouse/location concept in the public API.
 * Unavailable: customer — no buyer/customer resource exposed in the public API.
 * Unavailable: discount — no discount/coupon CRUD API exists in Etsy Open API v3.
 *
 * Omitted — the registry will return HTTP 501 automatically:
 *
 *   Variants (5)     — Etsy variations are property_id+value_id pairs
 *                       embedded in the inventory resource, not variant CRUD.
 *   Locations (2)    — Etsy shops don't have warehouse locations.
 *   Customers (5)    — no buyer/customer resource exposed.
 *   Discounts (5)    — no discount/coupon API.
 *   Order mutations (3) — create/update/cancel: sellers don't create orders.
 *   Fulfillment mutations (2) — update/cancel: no API for modifying shipments.
 *   Refund create (1) — refunds are read-only, generated by case management.
 *   Transaction create (1) — payments are read-only, generated by Etsy's
 *                             payment processing; there is no write API.
 *
 * Webhooks: Etsy does NOT have outgoing webhooks. verifyWebhook /
 * parseWebhookEvents are omitted.
 */

