import type {
  LogisticsAdapter,
  Credentials,
  QueryParams,
} from '../../adapter/interface'
import type { Shipment } from '../../schema/shipment'
import type { Order } from '../../schema/order'
import type { Warehouse } from '../../schema/warehouse'

import { buildAuthUrl, exchangeCredentials, refreshCredentials as doRefresh } from './auth'
import { ManhattanWmsClient } from './client'

import { transformOrder, type ManhattanWmsOrderResponse, type ManhattanWmsOrdersResponse } from './transform/order'
import { transformWarehouse, type ManhattanWmsFacilityResponse } from './transform/warehouse'
import { transformShipment, type ManhattanWmsShipmentResponse } from './transform/shipment'

export interface ManhattanWmsAdapterConfig {
  clientId?: string
  clientSecret?: string
}

export class ManhattanWmsAdapter implements LogisticsAdapter {
  readonly platform = 'manhattan-wms'
  readonly version = '1'

  private config: ManhattanWmsAdapterConfig

  constructor(config: ManhattanWmsAdapterConfig = {}) {
    this.config = config
  }

  // ── Auth ───────────────────────────────────────────────────────────────────

  getAuthUrl(state: string): string {
    return buildAuthUrl(state)
  }

  async exchangeCode(_code: string, _redirectUri: string): Promise<Credentials> {
    if (!this.config.clientId || !this.config.clientSecret) {
      throw new Error('manhattan-wms: clientId and clientSecret are required')
    }
    return exchangeCredentials({
      clientId: this.config.clientId,
      clientSecret: this.config.clientSecret,
    })
  }

  async refreshCredentials(credentials: Credentials): Promise<Credentials> {
    return doRefresh(credentials)
  }

  // ── Orders ─────────────────────────────────────────────────────────────────

  async listOrders(credentials: Credentials, params: QueryParams): Promise<Order[]> {
    const client = new ManhattanWmsClient(credentials)
    const res = await client.get<ManhattanWmsOrdersResponse>('/orders', {
      page: params.page,
      limit: params.limit,
    })
    return (res.orders ?? []).map(transformOrder)
  }

  async getOrder(credentials: Credentials, id: string): Promise<Order> {
    const client = new ManhattanWmsClient(credentials)
    const raw = await client.get<ManhattanWmsOrderResponse>(`/orders/${id}`)
    return transformOrder(raw)
  }

  // ── Warehouses ─────────────────────────────────────────────────────────────

  async listWarehouses(credentials: Credentials, params: QueryParams): Promise<Warehouse[]> {
    const client = new ManhattanWmsClient(credentials)
    const res = await client.get<{ facilities: ManhattanWmsFacilityResponse[] }>('/facilities', {
      page: params.page,
      limit: params.limit,
    })
    return (res.facilities ?? []).map(transformWarehouse)
  }

  async getWarehouse(credentials: Credentials, id: string): Promise<Warehouse> {
    const client = new ManhattanWmsClient(credentials)
    const raw = await client.get<ManhattanWmsFacilityResponse>(`/facilities/${id}`)
    return transformWarehouse(raw)
  }

  // ── Shipments ──────────────────────────────────────────────────────────────

  async getShipment(credentials: Credentials, id: string): Promise<Shipment> {
    const client = new ManhattanWmsClient(credentials)
    const raw = await client.get<ManhattanWmsShipmentResponse>(`/shipments/${id}`)
    return transformShipment(raw)
  }
}
