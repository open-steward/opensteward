import type {
  LogisticsAdapter,
  Credentials,
  QueryParams,
} from '../../adapter/interface'
import type { Shipment } from '../../schema/shipment'
import type { Order } from '../../schema/order'
import type { Warehouse } from '../../schema/warehouse'

import { buildAuthUrl, exchangeCredentials, refreshCredentials as doRefresh } from './auth'
import { InforWmsClient } from './client'

import { transformOrder, type InforWmsOrderResponse, type InforWmsOrdersResponse } from './transform/order'
import { transformWarehouse, type InforWmsWarehouseResponse } from './transform/warehouse'
import { transformShipment, type InforWmsShipmentResponse } from './transform/shipment'

export interface InforWmsAdapterConfig {
  clientId?: string
  clientSecret?: string
}

export class InforWmsAdapter implements LogisticsAdapter {
  readonly platform = 'infor-wms'
  readonly version = '1'

  private config: InforWmsAdapterConfig

  constructor(config: InforWmsAdapterConfig = {}) {
    this.config = config
  }

  // ── Auth ───────────────────────────────────────────────────────────────────

  getAuthUrl(state: string): string {
    return buildAuthUrl(state)
  }

  async exchangeCode(_code: string, _redirectUri: string): Promise<Credentials> {
    if (!this.config.clientId || !this.config.clientSecret) {
      throw new Error('infor-wms: clientId and clientSecret are required')
    }
    return exchangeCredentials({
      clientId: this.config.clientId,
      clientSecret: this.config.clientSecret,
    })
  }

  async refreshCredentials(credentials: Credentials): Promise<Credentials> {
    return doRefresh(credentials)
  }

  // ── Orders ─────────────────────────────────────────────────────────────────

  async listOrders(credentials: Credentials, params: QueryParams): Promise<Order[]> {
    const client = new InforWmsClient(credentials)
    const res = await client.get<InforWmsOrdersResponse>('/orders', {
      page: params.page,
      limit: params.limit,
    })
    return (res.orders ?? []).map(transformOrder)
  }

  async getOrder(credentials: Credentials, id: string): Promise<Order> {
    const client = new InforWmsClient(credentials)
    const raw = await client.get<InforWmsOrderResponse>(`/orders/${id}`)
    return transformOrder(raw)
  }

  // ── Warehouses ─────────────────────────────────────────────────────────────

  async listWarehouses(credentials: Credentials, params: QueryParams): Promise<Warehouse[]> {
    const client = new InforWmsClient(credentials)
    const res = await client.get<{ warehouses: InforWmsWarehouseResponse[] }>('/warehouses', {
      page: params.page,
      limit: params.limit,
    })
    return (res.warehouses ?? []).map(transformWarehouse)
  }

  async getWarehouse(credentials: Credentials, id: string): Promise<Warehouse> {
    const client = new InforWmsClient(credentials)
    const raw = await client.get<InforWmsWarehouseResponse>(`/warehouses/${id}`)
    return transformWarehouse(raw)
  }

  // ── Shipments ──────────────────────────────────────────────────────────────

  async getShipment(credentials: Credentials, id: string): Promise<Shipment> {
    const client = new InforWmsClient(credentials)
    const raw = await client.get<InforWmsShipmentResponse>(`/shipments/${id}`)
    return transformShipment(raw)
  }
}
