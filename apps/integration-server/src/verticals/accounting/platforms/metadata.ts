import type { UnsupportedPlatform, VerificationTier } from '@opensteward/shared'

export type PlatformCategory = 'accounting' | 'erp' | 'bookkeeping'

export type AuthType =
  | 'oauth2'     // authorization-code flow
  | 'oauth2_cc'  // client-credentials (PowerOffice)
  | 'api_key'    // static key passed at auth exchange
  | 'session'    // username+password or token-pair → session
  | 'local'      // no network auth (TallyPrime local server)

export interface PlatformMetadata {
  slug: string
  name: string
  description: string
  website: string
  category: PlatformCategory
  primary_color: string  // 6-digit hex e.g. "#2D6ADB"
  auth_type: AuthType
  hq_country: string     // ISO 3166-1 alpha-2
  docs_url: string
  pricing_url: string
  founded_year: number
  /** Optional curated set of OAuth scopes to surface as checkbox options on
   *  the admin configure page. Operators can still add unlisted scopes via
   *  the free-text fallback. */
  recommendedScopes?: ReadonlyArray<string>
  /** Unambiguously read-only OAuth scopes (a subset of `recommendedScopes`).
   *  Drives the read-only-by-default Connect Link policy. Omit when the
   *  platform offers no read-only scopes — links fall back to platform default. */
  readScopes?: ReadonlyArray<string>
  /** Adapter ignores per-link `overrideScopes` — scopes are configured at
   *  the OAuth-app level (e.g. Salesforce, Bitrix24). When false, the
   *  Connect Link admin form disables the scope-group dropdown. Default true. */
  supportsScopeOverride?: boolean
  /** When set, this platform is listed but cannot be connected or enabled —
   *  listed-but-not-connectable. `reason` is required and shown verbatim in
   *  admin, the catalog and API refusal errors; `issueUrl` optionally links
   *  a tracking issue. Existing connections keep working — only NEW
   *  connections and ENABLING refuse; disabling stays allowed. */
  unsupported?: UnsupportedPlatform
  /** How far this adapter has actually been exercised. Absent means
   *  scaffolded — generated but never run against the real API, which is
   *  where most of the catalog sits. Rungs, weakest first: `unit-tested`,
   *  `verified` (the platform's real API, sandbox or live). Provenance for each claim
   *  (who, when, against what) lives in `scripts/adapter-verification-audit.json`
   *  and is enforced by `pnpm check:adapter-verification`. */
  verification?: VerificationTier
}

