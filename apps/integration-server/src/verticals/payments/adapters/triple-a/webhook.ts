/**
 * TripleA webhook event parsing and signature verification.
 *
 * Triple-A signs every webhook notification with an HMAC-SHA256 signature
 * delivered in the `Triplea-Signature` HTTP header using the same
 * Stripe-style `t=<unix-timestamp>,v1=<hex-sig>` scheme:
 *
 *   signed_payload = `${timestamp}.${rawBody}`
 *   signature      = HMAC-SHA256(signed_payload, notify_secret) — hex-encoded
 *
 * Reference: https://developers.triple-a.io/docs/triplea-api-doc/96532c880a416-webhook-notifications
 *
 * The notify_secret is the shared secret configured on the payment/payout
 * request (or auto-generated by Triple-A for that request). Pass it as the
 * `secret` argument.
 *
 * Verification is fail-closed: any missing header, missing secret, bad
 * timestamp, or signature mismatch returns false — never throws.
 */

import { verifyStripeStyleSignature } from '@opensteward/shared'
import type { WebhookHandler } from '@opensteward/shared'
import type { WebhookEvent } from '../../schema/webhook'

/** Header name used by Triple-A for the signature. */
const SIGNATURE_HEADER = 'triplea-signature'

export function verifyWebhook(
  payload: Buffer,
  headers: Record<string, string>,
  secret: string,
): boolean {
  // Fail closed when no secret is configured.
  if (!secret) return false

  // Header names from HTTP frameworks are typically lowercased.
  const header = headers[SIGNATURE_HEADER] ?? headers['Triplea-Signature']

  return verifyStripeStyleSignature({
    rawBody: payload,
    header,
    secret,
  })
}

export function parseWebhookEvents(payload: Record<string, unknown>): WebhookEvent[] {
  const type =
    typeof payload['type'] === 'string'
      ? payload['type']
      : typeof payload['event'] === 'string'
        ? payload['event']
        : String(payload['type'] ?? '')
  const id = typeof payload['id'] === 'string' ? payload['id'] : undefined
  const dataObj =
    typeof payload['data'] === 'object' && payload['data'] !== null
      ? (payload['data'] as Record<string, unknown>)
      : {}
  const resourceId =
    typeof payload['resource_id'] === 'string'
      ? payload['resource_id']
      : typeof dataObj['id'] === 'string'
        ? dataObj['id']
        : ''
  return [
    {
      id,
      platform: 'triple-a',
      type,
      resourceType: 'unknown',
      action: 'unknown',
      resourceId,
      payload,
    },
  ]
}

export const TripleAWebhookHandler: WebhookHandler = {
  verifyWebhook,
  parseWebhookEvents,
}
