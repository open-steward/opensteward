import type {
  CollectionMethod,
  Subscription,
  SubscriptionItem,
  SubscriptionStatus,
} from '../../../schema/subscription'
import { optionalMinor, pickStr, strMap, toIsoDatetime } from './shared'

/**
 * Rapyd Subscription object, as List Subscriptions / Retrieve Subscription
 * document it (https://docs.rapyd.net/en/list-subscriptions.html,
 * https://docs.rapyd.net/en/retrieve-subscription.html). Only the documented
 * fields this transform reads are typed.
 *
 *   customer_token      "ID of the customer who pays for this subscription."
 *   billing             pay_automatically | send_invoice
 *   status              active | canceled | past_due | trialing | unpaid
 *   subscription_items  { data: [{ id, quantity, metadata, plan }], has_more, total_count, url }
 *   payment_method      "Payment method used for paying invoices generated by this subscription."
 *
 * The subscription carries no currency of its own, so `currency` is left out.
 */
export interface RawRapydSubscriptionPlan {
  id?: string
  amount?: number | string
  billing_scheme?: string
  currency?: string
  product?: { id?: string } | null
  [k: string]: unknown
}

export interface RawRapydSubscriptionItem {
  id?: string
  quantity?: number
  metadata?: Record<string, unknown> | null
  plan?: RawRapydSubscriptionPlan | null
  [k: string]: unknown
}

export interface RawRapydSubscription {
  id?: string
  customer_token?: string
  status?: string
  billing?: string
  subscription_items?: { data?: RawRapydSubscriptionItem[] | null } | null
  current_period_start?: number | string | null
  current_period_end?: number | string | null
  billing_cycle_anchor?: number | string | null
  trial_start?: number | string | null
  trial_end?: number | string | null
  canceled_at?: number | string | null
  cancel_at_period_end?: boolean
  payment_method?: string | null
  created_at?: number | string
  metadata?: Record<string, unknown> | null
  [k: string]: unknown
}

function mapStatus(status: unknown): SubscriptionStatus {
  switch (status) {
    case 'active':
      return 'active'
    case 'trialing':
      return 'trialing'
    case 'past_due':
      return 'past_due'
    case 'canceled':
      return 'cancelled'
    case 'unpaid':
      // "An error occurred in the payment for this subscription."
      return 'past_due'
    default:
      return 'unknown'
  }
}

function mapBilling(billing: unknown): CollectionMethod | undefined {
  // pay_automatically: "Rapyd generates a payment object, then attempts to pay
  // it using the designated payment method."
  if (billing === 'pay_automatically') return 'charge_automatically'
  if (billing === 'send_invoice') return 'send_invoice'
  return undefined
}

function mapItem(raw: RawRapydSubscriptionItem, subscriptionId: string): SubscriptionItem {
  const id = pickStr(raw.id)
  if (!id) throw new Error(`Rapyd subscription ${subscriptionId} has an item with no id`)
  const plan = raw.plan ?? undefined
  // A plan's `amount` is documented only for per_unit billing.
  const currency = pickStr(plan?.currency)
  const amount =
    plan?.billing_scheme === 'per_unit' && currency
      ? optionalMinor(plan.amount, currency)
      : undefined
  const metadata = raw.metadata ? strMap(raw.metadata) : undefined
  return {
    id,
    priceId: pickStr(plan?.id),
    productId: pickStr(plan?.product?.id),
    quantity: typeof raw.quantity === 'number' && raw.quantity >= 0 ? raw.quantity : undefined,
    amount,
    metadata,
  }
}

export function transformSubscription(raw: RawRapydSubscription): Subscription {
  const id = pickStr(raw.id)
  if (!id) throw new Error('Rapyd subscription has no id')
  const customerId = pickStr(raw.customer_token)
  if (!customerId) throw new Error(`Rapyd subscription ${id} has no customer_token`)
  const items = raw.subscription_items?.data
  return {
    id,
    externalId: id,
    customerId,
    status: mapStatus(raw.status),
    items: Array.isArray(items) ? items.map((i) => mapItem(i, id)) : [],
    currentPeriodStart: toIsoDatetime(raw.current_period_start),
    currentPeriodEnd: toIsoDatetime(raw.current_period_end),
    billingAnchor: toIsoDatetime(raw.billing_cycle_anchor),
    trialStart: toIsoDatetime(raw.trial_start),
    trialEnd: toIsoDatetime(raw.trial_end),
    cancelledAt: toIsoDatetime(raw.canceled_at),
    cancelAtPeriodEnd:
      typeof raw.cancel_at_period_end === 'boolean' ? raw.cancel_at_period_end : undefined,
    collectionMethod: mapBilling(raw.billing),
    defaultPaymentMethodId: pickStr(raw.payment_method),
    gateway: 'rapyd',
    metadata: strMap(raw.metadata),
    createdAt: toIsoDatetime(raw.created_at),
    raw,
  }
}
