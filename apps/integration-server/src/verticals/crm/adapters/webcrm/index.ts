/**
 * webCRM adapter for the CRM vertical.
 *
 * Maps the webCRM REST API to canonical CRM resources.
 * Docs: https://files.webcrm.com/index.html (Swagger)
 *
 * Auth: OAuth2 Bearer token
 * Notable:
 *   - Developed by Efficy, headquartered in Denmark
 *   - PascalCase field names throughout
 *   - "Person" entity = individual contact
 *   - "Organisation" entity = company
 *   - "Opportunity" entity = deal
 *
 * ── Coverage ─────────────────────────────────────────────────────────────
 *
 * Implemented (20):
 *   Contacts (Persons): list, get, create, update, delete
 *   Companies (Organisations): list, get, create, update, delete
 *   Deals (Opportunities): list, get, create, update, delete
 *   Pipelines: list
 *   Activities: list, get, create
 *   Notes: list, get, create
 *   Auth: getAuthUrl, exchangeCode, refreshCredentials
 *   Webhooks: verifyWebhook (stub), parseWebhookEvents (stub)
 */

