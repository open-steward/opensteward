import type { AuthorType, Message } from '../../../schema'
import {
  many2oneId,
  many2oneName,
  many2oneNum,
  meta,
  odooIso,
  strOrUndef,
  stripHtml,
  type Many2one,
} from '../values'

/**
 * A `mail.message` row in a ticket's chatter, as `search_read` returns it for
 * {@link MESSAGE_FIELDS}. Fields from addons/mail/models/mail_message.py
 * (odoo/odoo 14.0 and 19.0, the same names in both):
 *
 *   date = fields.Datetime('Date', default=fields.Datetime.now)
 *   body = fields.Html('Contents', default='', sanitize_style=True)
 *   attachment_ids = fields.Many2many('ir.attachment', …)
 *   model = fields.Char('Related Document Model')
 *   res_id = fields.Many2oneReference('Related Document ID', model_field='model')
 *   message_type = fields.Selection([('email', …), ('comment', 'Comment'), …])
 *   subtype_id = fields.Many2one('mail.message.subtype', 'Subtype', …)
 *   is_internal = fields.Boolean('Employee Only', help='Hide to public / portal
 *     users, independently from subtype configuration.')
 *   author_id = fields.Many2one('res.partner', 'Author', …)
 *
 * Only the attachment COUNT is surfaced: the canonical schema refuses
 * attachment content, and `email_from` is not read.
 */
export interface RawOdooMessage {
  id: number
  body?: string | false
  model?: string | false
  res_id?: number | false
  message_type?: string | false
  subtype_id?: Many2one
  is_internal?: boolean
  author_id?: Many2one
  attachment_ids?: number[] | false
  date?: string | false
  [key: string]: unknown
}

export const MESSAGE_FIELDS = [
  'id',
  'body',
  'model',
  'res_id',
  'message_type',
  'subtype_id',
  'is_internal',
  'author_id',
  'attachment_ids',
  'date',
]

/**
 * `message_type` values a person wrote: "'email': generated by an incoming
 * email e.g. mailgateway", "'comment': generated by user input e.g. through
 * discuss or composer" (mail_message.py 19.0). The rest are system tracking,
 * automated and per-user notifications. Both values exist from 14.0 on.
 */
export const HUMAN_MESSAGE_TYPES = ['email', 'comment']

/** What the adapter looked up beside the page of messages. */
export interface MessageContext {
  /** mail.message.subtype ids whose `internal` flag is set ("Internal Only"). */
  internalSubtypes: ReadonlySet<number>
  /** res.partner id → id of the internal (non-share) res.users it belongs to. */
  agentByPartner: ReadonlyMap<number, number>
}

/**
 * Visibility is Odoo's own rule for what portal users (customers) may read:
 * `['&', '&', ('is_internal', '=', False), ('subtype_id', '!=', False),
 * ('subtype_id.internal', '=', False)]` (mail_message.py 19.0,
 * `_get_search_domain_share`). Anything else is employee-only, an internal note.
 *
 * The author is a res.partner. When that partner is an internal user's, the
 * author is that user (the id `listUsers` returns); otherwise it is the
 * partner (the id `listContacts` returns).
 */
export function transformMessage(raw: RawOdooMessage, ctx: MessageContext): Message {
  const subtype = many2oneNum(raw.subtype_id)
  const isPublic =
    raw.is_internal !== true && subtype !== undefined && !ctx.internalSubtypes.has(subtype)
  const authorPartner = many2oneNum(raw.author_id)
  const agent = authorPartner !== undefined ? ctx.agentByPartner.get(authorPartner) : undefined
  let authorType: AuthorType
  let authorId: string
  if (agent !== undefined) {
    authorType = 'user'
    authorId = String(agent)
  } else if (authorPartner !== undefined) {
    authorType = 'contact'
    authorId = String(authorPartner)
  } else {
    authorType = 'unknown'
    authorId = ''
  }
  const body = strOrUndef(raw.body)
  return {
    id: String(raw.id),
    externalId: String(raw.id),
    ticketId: typeof raw.res_id === 'number' && raw.res_id ? String(raw.res_id) : '',
    authorId,
    authorType,
    body: body ? stripHtml(body) : '',
    type: isPublic ? 'public' : 'internal',
    attachmentCount: Array.isArray(raw.attachment_ids) ? raw.attachment_ids.length : undefined,
    createdAt: odooIso(raw.date) ?? new Date(0).toISOString(),
    platform: 'odoo-helpdesk',
    metadata: meta({
      messageType: strOrUndef(raw.message_type),
      subtype: many2oneName(raw.subtype_id),
      authorPartnerId: many2oneId(raw.author_id),
    }),
    raw,
  }
}
