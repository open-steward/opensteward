/**
 * Payments metrics. Paths are camelCase; enums are lower case. Amounts are
 * integer minor units with a top-level `currency` (flat, not nested). Charge
 * metrics anchor on `createdAt` (`capturedAt` is often null).
 *
 * Common sets:
 *   SUCCESS  — charges whose money was captured at some point: succeeded,
 *              partially_refunded, refunded, disputed
 *   ATTEMPT  — SUCCESS plus failed (pending and cancelled never settled)
 *   DISPUTE  — disputes proper: the `warning_*` statuses are early fraud
 *              warnings, not chargebacks
 *
 * Money is never combined across currencies: every money metric is grouped
 * by currency and ratios of amounts are per currency. Count metrics may be
 * added across currencies. Fields that only some gateways fill in (`fee`,
 * `arrivalDate`, `availableOn`, `failureCode`, `dueDate`, `paidAt`) are
 * declared as `coverage` on the ratio and duration metrics that read them.
 */
import type { MetricFilter, ResourceMetricDefinition } from '../types'

export const SUCCESS_STATUSES = ['succeeded', 'partially_refunded', 'refunded', 'disputed']
const SUCCESS: MetricFilter = { field: 'status', op: 'in', value: SUCCESS_STATUSES }
const ATTEMPT: MetricFilter = {
  field: 'status',
  op: 'in',
  value: [...SUCCESS_STATUSES, 'failed'],
}
const FAILED: MetricFilter = { field: 'status', op: 'eq', value: 'failed' }

const REFUND_DONE: MetricFilter[] = [
  { field: 'status', op: 'eq', value: 'succeeded' },
  // An uncaptured-charge release is an authorisation void, not a refund.
  { field: 'reason', op: 'ne', value: 'expired_uncaptured_charge' },
]

const WARNING_STATUSES = ['warning_needs_response', 'warning_under_review', 'warning_closed']
const DISPUTE: MetricFilter = { field: 'status', op: 'not_in', value: WARNING_STATUSES }
const DISPUTE_OPEN_STATUSES = ['needs_response', 'warning_needs_response']

const OPEN_INVOICE: MetricFilter = { field: 'status', op: 'eq', value: 'open' }
const ISSUED_INVOICE: MetricFilter = { field: 'status', op: 'not_in', value: ['draft', 'void'] }

