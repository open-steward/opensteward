/**
 * CRM metrics. Paths are snake_case. CRM money is in MAJOR units
 * (`amountUnit: 'major'` on every money measure); a deal's value is a
 * `{ amount, currency }` pair.
 *
 * Outcomes are read from the raw platform `status` string — there is no
 * normalised outcome or `closed_at` on the canonical deal (design §7):
 *   WON    — `status` in_ci won / closed won / closedwon / closed_won
 *   LOST   — the same pattern with `lost`
 *   OPEN   — anything else that is not `deleted` (a deal with no status is open)
 * Every metric that depends on that split carries a `note` saying so. A
 * won or lost deal is anchored on `close_date` (expected OR actual — the
 * schema does not say which, so a won deal's `close_date` is its close).
 *
 * `not_in` is case-sensitive while `in_ci` is not, so OPEN excludes every
 * common casing of the won / lost / deleted labels (`caseVariants`).
 *
 * Owners are ids only: there is no CRM user resource to resolve names from.
 * Company and deal names are `internal` (not PII) and may label rows.
 */
import type { Measure, MetricFilter, ResourceMetricDefinition } from '../types'

export const WON_STATUSES = ['won', 'closed won', 'closedwon', 'closed_won']
export const LOST_STATUSES = ['lost', 'closed lost', 'closedlost', 'closed_lost']

/** lower, UPPER, Capitalised, Title Case Words and camelCase of each label. */
export function caseVariants(labels: readonly string[]): string[] {
  const out = new Set<string>()
  for (const l of labels) {
    const words = l.split(/[ _]+/)
    const cap = (w: string) => w.charAt(0).toUpperCase() + w.slice(1)
    out.add(l)
    out.add(l.toUpperCase())
    out.add(cap(l))
    for (const sep of [' ', '_', '']) out.add(words.map(cap).join(sep))
    out.add(words.map((w, i) => (i === 0 ? w : cap(w))).join(''))
  }
  return [...out]
}

const STATUS_NOTE =
  "Based on the platform's status label (won / closed won / lost / closed lost); platforms that do not set a status are not counted."

export const IS_WON: MetricFilter = { field: 'status', op: 'in_ci', value: WON_STATUSES }
export const IS_CLOSED: MetricFilter = {
  field: 'status',
  op: 'in_ci',
  value: [...WON_STATUSES, ...LOST_STATUSES],
}
export const OPEN_DEAL: MetricFilter = {
  field: 'status',
  op: 'not_in',
  value: caseVariants([...WON_STATUSES, ...LOST_STATUSES, 'deleted']),
}
const IS_LOST: MetricFilter = { field: 'status', op: 'in_ci', value: LOST_STATUSES }

const VALUE_SUM: Measure = {
  op: 'sum',
  field: 'value.amount',
  currencyField: 'value.currency',
  amountUnit: 'major',
}
const VALUE_AVG: Measure = {
  op: 'avg',
  field: 'value.amount',
  currencyField: 'value.currency',
  amountUnit: 'major',
}

/** Percent of open deals that carry `field`. */
function dealCompleteness(
  key: string,
  label: string,
  field: string,
): ResourceMetricDefinition {
  return {
    id: `crm.deal_completeness_${key}`,
    title: `Open deals with ${label}`,
    description: `Share of open deals that have ${label}: the trust level of every forecast that reads it.`,
    vertical: 'crm',
    resourceType: 'deals',
    section: 'quality',
    kind: 'ratio',
    snapshot: true,
    filters: [OPEN_DEAL],
    numerator: { measure: { op: 'count' }, filters: [{ field, op: 'not_null' }] },
    denominator: { measure: { op: 'count' } },
    coverage: [field],
    note: STATUS_NOTE,
  }
}

/** Percent of contacts that carry `field`. */
function contactCompleteness(
  key: string,
  label: string,
  field: string,
): ResourceMetricDefinition {
  return {
    id: `crm.contact_completeness_${key}`,
    title: `Contacts with ${label}`,
    description: `Share of contacts that have ${label}.`,
    vertical: 'crm',
    resourceType: 'contacts',
    section: 'quality',
    kind: 'ratio',
    snapshot: true,
    numerator: { measure: { op: 'count' }, filters: [{ field, op: 'not_null' }] },
    denominator: { measure: { op: 'count' } },
    coverage: [field],
  }
}

