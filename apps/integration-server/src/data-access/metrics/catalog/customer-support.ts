/**
 * Customer-support metrics. Paths are camelCase; enums are lower case. The
 * ticket `subject` is PII (the customer's own words) and is never read;
 * agent and requester names are PII too, so agents, requesters and owners
 * are shown by id. Tag and team names are `internal` and label rows.
 *
 *   OPEN   — `status` not resolved / closed (an `unknown` status counts as open)
 *   SOLVED — `status` resolved or closed
 *
 * `resolvedAt` is the platform's own field and some platforms approximate it
 * from `updatedAt` (Zendesk among them), so durations that read it say so.
 * Not computable from the canonical ticket, and so absent here: first
 * response time, SLA attainment and breach, reopen rate, one-touch
 * resolution, and a backlog rebuilt day by day (design §7).
 */
