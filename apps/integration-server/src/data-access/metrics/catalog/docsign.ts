/**
 * Docsign metrics. Paths are camelCase; enums are lower case (with `unknown`).
 * Only `envelopes` and `templates` are synced: signers and the audit trail are
 * not, so there are no per-signer metrics. The envelope `subject`, `message`,
 * `senderEmail` and `senderName` are PII and never read; senders are shown by
 * `senderId`.
 *
 * Common sets:
 *   IN_FLIGHT — status `sent` or `delivered` (waiting on a signer)
 *   TERMINAL  — completed, declined, voided or expired (the envelope is over)
 *
 * Outcome rates divide by TERMINAL envelopes only, so envelopes still waiting
 * do not pull a rate down. They are grouped by the day the envelope was sent.
 */
