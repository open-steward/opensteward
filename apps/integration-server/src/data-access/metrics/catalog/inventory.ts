/**
 * Inventory metrics. Paths are camelCase; enums are lower case. Purchase-order
 * money is a plain `totalAmount` in minor units with a sibling `currency`.
 *
 * Stock levels are a current-state row per (product, location), so every
 * stock metric is a snapshot. Inventory VALUE (quantity × product cost) needs
 * a join to `products.cost` and is not chartable here.
 *
 * Common sets (research §4):
 *   OPEN_PO    — status `sent` or `partially_received`
 *   COMMITTED  — every PO that is not a draft or cancelled (money that is spent)
 *   OVERDUE_PO — OPEN_PO whose `expectedAt` day is before today
 *   SHRINKAGE  — adjustments with reason damage, theft, lost or expiration
 */
