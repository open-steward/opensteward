/**
 * Logistics metrics. Paths are camelCase; enums are UPPER case (label enums
 * add a lower-case `unknown`). A shipment's cost is `{ amount, currency }` in
 * minor units, so the currency of a money measure is its sibling
 * (`cost.currency`). Addresses are PII, so there are no country metrics.
 *
 * Dates are stored as ISO strings; comparisons and now-relative filters work
 * on the day.
 *
 * Common sets (research §3):
 *   DELIVERED  — `status = DELIVERED`
 *   ELIGIBLE   — DELIVERED with both `estimatedDeliveryAt` and `actualDeliveryAt`;
 *                on time = `actualDeliveryAt <= estimatedDeliveryAt` (by day)
 *   IN_FLIGHT  — LABEL_CREATED, IN_TRANSIT, OUT_FOR_DELIVERY, EXCEPTION
 *   STUCK      — IN_FLIGHT whose `updatedAt` is more than N days old (a proxy:
 *                there is no last-scan time on the shipment)
 *
 * Shipments carry no `shippedAt`, so transit time starts at `createdAt`.
 */
