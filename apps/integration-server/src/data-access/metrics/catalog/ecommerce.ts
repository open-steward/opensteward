/**
 * Ecommerce metrics. Paths are camelCase; enums are UPPER case. Money is a
 * `{ amount, currency }` pair in minor units, so the currency field of a
 * money measure is its sibling (`totalPrice.currency`).
 *
 * Common sets:
 *   COUNTABLE — an order that stands: not cancelled and not voided
 *   BACKLOG   — paid (or authorised) orders not yet fully fulfilled and not
 *               cancelled. Orders the platform reports no fulfilment status
 *               for are not in it.
 *
 * Money is never combined across currencies; ratios of amounts are per
 * currency. Guest checkouts have no `customerId`: customer metrics see only
 * identified customers and report the rest as unattributed. `refunds.reason`
 * and every address are personal data and are never read.
 */
import type { MetricFilter, ResourceMetricDefinition } from '../types'

