/**
 * Accounting metrics. Paths are camelCase. Amounts are integer minor units;
 * `contactId` is `internal` (ids are shown, names are personal data).
 *
 * Common sets (design §6):
 *   ISSUED_AR — `invoices` that are not bills or credit notes (a missing
 *               `type` counts as an invoice) and not DRAFT / VOIDED / DELETED
 *   OPEN_AR   — ISSUED_AR with `balanceAmount > 0` and status ≠ PAID
 *   OVERDUE   — OPEN_AR with `dueAt` before today. Never status = OVERDUE:
 *               platforms stop updating it.
 *   ISSUED_AP / OPEN_AP — the same on `bills`
 */
import type { Measure, MetricFilter, ResourceMetricDefinition } from '../types'

/** `invoices` rows that are receivables: not a bill or a credit note. */
export const AR_DOCUMENT: MetricFilter = {
  field: 'type',
  op: 'not_in',
  value: ['BILL', 'CREDITMEMO'],
}
const NOT_DRAFT_OR_VOID: MetricFilter = {
  field: 'status',
  op: 'not_in',
  value: ['DRAFT', 'VOIDED', 'DELETED'],
}
const UNPAID: MetricFilter[] = [
  { field: 'status', op: 'not_in', value: ['DRAFT', 'VOIDED', 'DELETED', 'PAID'] },
  { field: 'balanceAmount', op: 'gt', value: 0 },
]

/** Due day before today. */
const PAST_DUE: MetricFilter = { field: 'dueAt', op: 'before_now' }

const COUNT: Measure = { op: 'count' }
const TOTAL: Measure = { op: 'sum', field: 'totalAmount', currencyField: 'currency' }
const BALANCE: Measure = { op: 'sum', field: 'balanceAmount', currencyField: 'currency' }
const PAID: Measure = { op: 'sum', field: 'paidAmount', currencyField: 'currency' }
const TAX: Measure = { op: 'sum', field: 'taxAmount', currencyField: 'currency' }

export const ISSUED_AR: MetricFilter[] = [AR_DOCUMENT, NOT_DRAFT_OR_VOID]
export const OPEN_AR: MetricFilter[] = [AR_DOCUMENT, ...UNPAID]
export const ISSUED_AP: MetricFilter[] = [NOT_DRAFT_OR_VOID]
