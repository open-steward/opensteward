#!/usr/bin/env node
/**
 * `generate-status-enums` — extract each entity's canonical `status`
 * vocabulary from the published OpenAPI document, for the MCP tool
 * descriptions.
 *
 * Four review rounds reported the normalized status enum as "undefined". It
 * never was — every entity declares a per-entity enum and each is published in
 * `docs/openapi/openapi.yaml`. But an MCP tool description advertises only its
 * INPUT schema, so from an agent's side a defined vocabulary and an undefined
 * one look identical, and a client could not learn that `PARTIALLY_PAID`
 * exists without reading the spec by hand.
 *
 * GENERATED rather than hand-listed in `resources.ts` for the obvious reason:
 * a hand-maintained copy drifts from the schemas silently, which is the exact
 * failure this is meant to end. `resources.ts` deliberately carries no runtime
 * dependency on integration-server's source, so generation is the same answer
 * the CLI already uses for the same constraint.
 *
 * Run via `pnpm --filter @opensteward/mcp-server run generate`, which
 * `docs:all` invokes; `check:docs` then fails a PR that changes a status enum
 * without regenerating.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { RESOURCES } from '../src/resources.js'

// This package is ESM ("type": "module"), so `__dirname` does not exist.
const HERE = dirname(fileURLToPath(import.meta.url))

const REPO_ROOT = resolve(HERE, '../../..')
const SPEC = join(REPO_ROOT, 'docs/openapi/openapi.json')
const OUT = join(HERE, '../src/generated/status-enums.ts')

interface Schema {
  properties?: Record<string, { enum?: unknown[] }>
}

/**
 * Match a resource to its schema by NORMALISING both sides rather than by
 * guessing a plural.
 *
 * The spec prefixes canonical schemas with their vertical (`AccountingInvoice`)
 * and sometimes suffixes them (`DocsignEnvelopeSchema`), while the registry
 * keys on the REST path segment (`invoices`, `envelopes`). Stripping a
 * trailing `Schema`, then a trailing `s`, and lowercasing makes the two
 * comparable without a table of irregular plurals to maintain.
 *
 * Iterating RESOURCES (rather than the spec) is deliberate: it means every key
 * emitted corresponds to a tool that actually exists. Walking the spec instead
 * produced 26 orphans — internal `SyncJob` states and `…Schema` wrappers that
 * are not entities at all.
 */
/** Schema-name prefixes, matching the vertical slugs the registry uses. */
const VERTICALS = [
  'accounting',
  'crm',
  'ecommerce',
  'logistics',
  'payments',
  'docsign',
  'projects',
  'customerSupport',
  'inventory',
] as const

function normalise(v: string): string {
  return v
    .toLowerCase()
    .replace(/schema$/, '')
    .replace(/s$/, '')
}

function main(): void {
  const spec = JSON.parse(readFileSync(SPEC, 'utf8')) as {
    components?: { schemas?: Record<string, Schema> }
  }
  const schemas = spec.components?.schemas ?? {}

  // Index the spec's status enums by (vertical, normalised entity).
  const byVerticalEntity = new Map<string, string[]>()
  for (const [name, schema] of Object.entries(schemas)) {
    const statusEnum = schema.properties?.['status']?.enum
    if (!Array.isArray(statusEnum) || statusEnum.length === 0) continue
    const lower = name.toLowerCase()
    // `customerSupport` -> `customersupport` so the prefix test matches the
    // schema naming, while the emitted key keeps the hyphen the registry uses.
    const vertical = VERTICALS.find((v) => lower.startsWith(v.toLowerCase()))
    if (!vertical) continue
    const entity = normalise(name.slice(vertical.length))
    if (!entity) continue
    byVerticalEntity.set(`${vertical.toLowerCase()}:${entity}`, statusEnum.map(String))
  }

  const out: Record<string, string[]> = {}
  for (const r of RESOURCES) {
    const verticalLookup = r.vertical === 'customer-support' ? 'customersupport' : r.vertical
    const found = byVerticalEntity.get(`${verticalLookup}:${normalise(r.path)}`)
    if (found) out[`${r.vertical}:${r.path}`] = found
  }

  const keys = Object.keys(out).sort()
  const body = keys.map((k) => `  '${k}': [${out[k]!.map((v) => `'${v}'`).join(', ')}],`).join('\n')

  mkdirSync(dirname(OUT), { recursive: true })
  writeFileSync(
    OUT,
    `// AUTOGENERATED — do not edit by hand.
// Source: docs/openapi/openapi.json
// Regenerate via: pnpm --filter @opensteward/mcp-server run generate
//
// Each entity's canonical \`status\` vocabulary, keyed \`<vertical>:<path>\` to
// match the tool registry. Surfaced in tool descriptions because an MCP tool
// advertises only its input schema, so an agent otherwise has no way to learn
// what \`status\` may contain.
//
// \`unknown\` is a real member: \`withUnknown\` appends it to every canonical
// status enum, meaning "the platform said something we could not map".

export const STATUS_ENUMS: Readonly<Record<string, readonly string[]>> = {
${body}
}
`,
  )
  console.log(`wrote ${OUT} — ${keys.length} entities with a status vocabulary`)
}

main()
