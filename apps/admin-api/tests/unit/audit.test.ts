/**
 * Audit-log registry tests.
 *
 * The registry is the source of truth for `(action, detail)` pairs that
 * `writeAudit` accepts. These tests pin three things:
 *   1. Known shapes round-trip (runtime: write succeeds, read returns the
 *      reassembled discriminated-union variant).
 *   2. The TypeScript types reject mismatched detail shapes — covered by
 *      `@ts-expect-error` directives. Vitest doesn't typecheck on its own,
 *      but a stray `git grep` for stale `@ts-expect-error`s catches the
 *      directives if the underlying signature is ever loosened.
 *   3. The generated OpenAPI snapshot expresses the discriminated union
 *      under `components.schemas.AuditEntry.detail`. The snapshot is
 *      generated by `pnpm docs:admin-api-openapi`; this test asserts on
 *      the committed file so a drift between source and artifact is
 *      caught at PR time.
 */
import { describe, it, expect, afterEach } from 'vitest'
import { resolve } from 'path'
import { readFileSync } from 'fs'
import { openDb } from '@opensteward/shared'
import { AdminStore } from '../../src/core/db/admin-store'
import {
  AUDIT_ACTION_VALUES,
  AUDIT_DETAIL_DOC_GROUPS,
  AuditDetailUnion,
} from '../../src/core/db/audit-actions'

describe('audit registry', () => {
  let store: AdminStore

  afterEach(async () => {
    await store?.close()
  })

  async function open() {
    const handle = await openDb({ sqlitePath: ':memory:' })
    store = await AdminStore.create(handle)
    return store
  }

  // ── Round-trip: typed write → SQLite → parsed read ───────────

  it('writes user.create with the typed detail', async () => {
    const s = await open()
    await s.writeAudit('u', 'user.create', undefined, undefined, {
      username: 'bob',
      role: 'viewer',
    })
    const row = (await s.listAudit()).find((e) => e.action === 'user.create')
    expect(row).toBeDefined()
    expect(row!.detail).toBe('{"username":"bob","role":"viewer"}')
  })

  it('writes sso.provider.create with the typed detail', async () => {
    const s = await open()
    await s.writeAudit('u', 'sso.provider.create', undefined, 'idp-1', {
      protocol: 'saml',
      slug: 'acme',
    })
    const row = (await s.listAudit()).find((e) => e.action === 'sso.provider.create')
    expect(row).toBeDefined()
    expect(JSON.parse(row!.detail!)).toEqual({ protocol: 'saml', slug: 'acme' })
  })

  it('writes a no-payload action without a detail argument', async () => {
    const s = await open()
    await s.writeAudit('u', 'user.login')
    const row = (await s.listAudit()).find((e) => e.action === 'user.login')
    expect(row).toBeDefined()
    expect(row!.detail).toBeNull()
  })

  it('accepts the object form with a labelled detail', async () => {
    const s = await open()
    await s.writeAudit({
      userId: 'u',
      action: 'scope_group.create',
      vertical: 'accounting',
      targetId: '7',
      detail: { name: 'Read-only', platform: 'xero' },
    })
    const row = (await s.listAudit()).find((e) => e.action === 'scope_group.create')
    expect(row).toBeDefined()
    expect(JSON.parse(row!.detail!)).toEqual({ name: 'Read-only', platform: 'xero' })
  })

  it('parses every persisted row back into the discriminated union', async () => {
    const s = await open()
    await s.writeAudit('u', 'user.create', undefined, undefined, {
      username: 'bob',
      role: 'viewer',
    })
    await s.writeAudit('u', 'connect_link_template.create', undefined, 't-1', {
      name: 'Demo',
      tenantId: 'default',
    })
    await s.writeAudit('u', 'connection.delete', 'accounting', 'conn-1')
    const rows = await s.listAudit()
    for (const row of rows) {
      // Skip rows for actions the current registry doesn't recognise —
      // the assert here is forward-compat only; the audit handler uses
      // the same `safeParse` and surfaces those as `null`.
      const candidate = { action: row.action, ...(row.detail ? JSON.parse(row.detail) : {}) }
      const parsed = AuditDetailUnion.safeParse(candidate)
      // Every action this test wrote (plus the boot `schema.migrate` row)
      // is in the registry, so every parse must succeed.
      expect(parsed.success).toBe(true)
    }
  })

  // ── TypeScript-level shape mismatch is a compile error ───────
  //
  // These two assertions are about the *static* contract: passing a
  // shape that doesn't match the literal `action`'s registered detail
  // must fail to compile. We can't run tsc inside vitest without extra
  // infra, but `@ts-expect-error` makes tsc itself the enforcer — the
  // directive errors if the line below it *doesn't* error, which is the
  // exact signal we want (drop the registry constraint, lose the
  // directive). The runtime SQL insert still happens, so the assertions
  // simply confirm the row was written; the value of these tests is the
  // type-check signal.

  it('detail shape mismatch is a TypeScript error (user.create)', async () => {
    const s = await open()
    // @ts-expect-error — `user.create` requires `{ username, role }`,
    // not `{ wrong: true }`. Removing the registry constraint would
    // make this line valid and break the expect-error directive, which
    // is the failure mode this test guards against.
    await s.writeAudit('u', 'user.create', undefined, undefined, { wrong: true })
    const row = (await s.listAudit()).find((e) => e.action === 'user.create')
    expect(row).toBeDefined()
  })

  it('unknown action literal is a TypeScript error', async () => {
    const s = await open()
    // @ts-expect-error — `'not-in-the-registry'` is not part of the
    // `AuditAction` union. New writers must add a branch to
    // `audit-actions.ts` before the call site compiles.
    await s.writeAudit('u', 'not-in-the-registry')
    const row = (await s.listAudit()).find((e) => e.action === 'not-in-the-registry')
    expect(row).toBeDefined()
  })

  // ── OpenAPI snapshot: AuditEntry.detail is the union ─────────

  it('OpenAPI snapshot models AuditEntry.detail as the discriminated union', () => {
    const specPath = resolve(__dirname, '../../../../docs/openapi/admin-api.openapi.json')
    const spec = JSON.parse(readFileSync(specPath, 'utf8')) as {
      components: { schemas: Record<string, { properties?: Record<string, unknown>; oneOf?: unknown[]; anyOf?: unknown[]; discriminator?: { propertyName: string } }> }
    }
    const components = spec.components.schemas
    expect(components.AuditEntry).toBeDefined()
    // `AuditEntry.detail` is `AuditDetail | null` — generated as
    // `{ anyOf: [{ $ref: '.../AuditDetail' }, { type: 'null' }] }`.
    const detail = (components.AuditEntry.properties as Record<string, { anyOf?: Array<{ $ref?: string; type?: string }> }>).detail
    expect(detail).toBeDefined()
    expect(Array.isArray(detail.anyOf)).toBe(true)
    const ref = detail.anyOf!.find((b) => typeof b.$ref === 'string')?.$ref
    expect(ref).toBe('#/components/schemas/AuditDetail')

    // `AuditDetail` itself MUST be a discriminated union keyed on `action`.
    const union = components.AuditDetail
    expect(union).toBeDefined()
    const branches = (union.oneOf ?? union.anyOf) as unknown[] | undefined
    expect(Array.isArray(branches)).toBe(true)
    expect(branches!.length).toBeGreaterThan(10) // sanity: >10 shapes today
    expect(union.discriminator).toBeDefined()
    expect(union.discriminator!.propertyName).toBe('action')

    // Published by SHAPE, not by action: the writer union's 72 per-action
    // variants collapse to a couple of dozen components, and the 35 actions
    // that carry nothing but `action` share one branch whose `action` is an
    // enum. Every action still maps to exactly one branch.
    const published = Object.keys(components).filter((k) => k.startsWith('AuditDetail'))
    expect(published.length).toBeLessThan(AUDIT_ACTION_VALUES.length / 2)
    const actionOnly = components.AuditDetailActionOnly as {
      properties?: { action?: { enum?: string[] } }
    }
    expect(actionOnly).toBeDefined()
    expect(actionOnly.properties?.action?.enum).toEqual(
      expect.arrayContaining(['user.delete', 'user.login']),
    )
    expect(Object.keys(actionOnly.properties ?? {})).toEqual(['action'])
    const mapping = (union.discriminator as { mapping?: Record<string, string> }).mapping ?? {}
    expect(Object.keys(mapping).sort()).toEqual([...AUDIT_ACTION_VALUES].sort())
    // The writer union itself is not published — only the grouped view is.
    expect(components.AuditDetailByAction).toBeUndefined()
    expect(components.AuditDetailUserDelete).toBeUndefined()

    // Spot-check a couple of variants are present + carry their literal
    // `action` discriminator.
    const variant = components.AuditDetailUserCreate as {
      properties?: { action?: { const?: string; enum?: string[] } }
    }
    expect(variant).toBeDefined()
    const lit = variant.properties?.action
    expect(lit?.const === 'user.create' || lit?.enum?.[0] === 'user.create').toBe(true)
  })
})

describe('AuditDetailDoc groups the writer union by shape', () => {
  it('covers every action exactly once', () => {
    const covered = AUDIT_DETAIL_DOC_GROUPS.flatMap((g) => g.actions)
    expect([...covered].sort()).toEqual([...AUDIT_ACTION_VALUES].sort())
  })

  it('keeps a single-action shape under its original component id', () => {
    const migrate = AUDIT_DETAIL_DOC_GROUPS.find((g) => g.actions.includes('schema.migrate'))
    expect(migrate?.id).toBe('AuditDetailSchemaMigrate')
    expect(migrate?.actions).toEqual(['schema.migrate'])
  })

  it('names a shared shape after its fields, and the field-less one ActionOnly', () => {
    const provider = AUDIT_DETAIL_DOC_GROUPS.find((g) => g.actions.includes('sso.scim.provision'))
    expect(provider?.id).toBe('AuditDetailProviderId')
    expect(provider?.fields).toEqual(['providerId'])
    const bare = AUDIT_DETAIL_DOC_GROUPS.find((g) => g.id === 'AuditDetailActionOnly')
    expect(bare?.fields).toEqual([])
    expect(bare?.actions.length).toBeGreaterThan(20)
  })
})
